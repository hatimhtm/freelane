/// Material 3 Expressive's shapes, drawn from the same polygons the phone uses (androidx MaterialShapes, normalized to
/// a unit square). Each run of eight numbers is one cubic: anchor, control, control, anchor. Scaled to the frame
/// exactly as Compose's `RoundedPolygon.toShape()` does, so a badge or a sticker is the same shape on both.
struct MaterialPolygon: Shape {
    let cubics: [CGFloat]
    func path(in rect: CGRect) -> Path {
        var p = Path()
        guard cubics.count >= 8 else { return p }
        func pt(_ i: Int) -> CGPoint { CGPoint(x: rect.minX + cubics[i] * rect.width, y: rect.minY + cubics[i + 1] * rect.height) }
        p.move(to: pt(0))
        var i = 0
        while i + 7 < cubics.count {
            p.addCurve(to: pt(i + 6), control1: pt(i + 2), control2: pt(i + 4))
            i += 8
        }
        p.closeSubpath()
        return p
    }
}

enum ExpressiveShape {
    case cookie12, cookie9, cookie6, clover, flower, burst, squircle, circle

    var shape: AnyShape {
        switch self {
        case .cookie12: return AnyShape(MaterialPolygon(cubics: MaterialShapeData.cookie12))
        case .cookie9:  return AnyShape(MaterialPolygon(cubics: MaterialShapeData.cookie9))
        case .cookie6:  return AnyShape(MaterialPolygon(cubics: MaterialShapeData.cookie6))
        case .clover:   return AnyShape(MaterialPolygon(cubics: MaterialShapeData.clover4))
        case .flower:   return AnyShape(MaterialPolygon(cubics: MaterialShapeData.flower))
        // The sticker: Material's soft burst, rounded at every point.
        case .burst:    return AnyShape(MaterialPolygon(cubics: MaterialShapeData.softBurst))
        // GCash: Material's rounded square, as on the phone.
        case .squircle: return AnyShape(MaterialPolygon(cubics: MaterialShapeData.square))
        case .circle:   return AnyShape(Circle())
        }
    }
}

